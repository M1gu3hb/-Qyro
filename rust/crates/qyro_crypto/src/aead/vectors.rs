#[test]
fn the_schema_rejects_what_it_says_it_rejects() {
    let schema: Value = serde_json::from_str(SCHEMA).expect("valid JSON");
    let original: Value = serde_json::from_str(COMMITTED).expect("valid JSON");

    // A tag of the wrong width. Sixteen bytes is the suite; anything else is a
    // different algorithm wearing the same name.
    let mut short_tag = original.clone();
    short_tag["initiator_to_responder_frames"][0]["tag"] = json!("00112233");
    assert!(validate(&short_tag, &schema, "").is_err(), "short tag");

    // A truncated session id: eight bytes is the wire width.
    let mut truncated = original.clone();
    truncated["session"]["session_id"] = json!("00112233");
    assert!(
        validate(&truncated, &schema, "").is_err(),
        "short session id"
    );

    // Associated data that is not a whole header.
    let mut short_aad = original.clone();
    short_aad["initiator_to_responder_frames"][0]["associated_data"] = json!("0011");
    assert!(validate(&short_aad, &schema, "").is_err(), "short header");

    // Uppercase hex: one value, one spelling.
    let mut uppercase = original.clone();
    uppercase["session"]["session_id"] = json!(
        original["session"]["session_id"]
            .as_str()
            .expect("string")
            .to_uppercase()
    );
    assert!(validate(&uppercase, &schema, "").is_err(), "uppercase hex");

    // An empty frame list satisfies every other rule and proves nothing.
    let mut empty = original.clone();
    empty["initiator_to_responder_frames"] = json!([]);
    assert!(validate(&empty, &schema, "").is_err(), "no frames");

    // An unknown property, and a missing one.
    let mut extra = original.clone();
    extra["session"]["surprise"] = json!("00");
    assert!(validate(&extra, &schema, "").is_err(), "unknown property");

    let mut missing = original.clone();
    missing["session"]
        .as_object_mut()
        .expect("object")
        .remove("session_id");
    assert!(validate(&missing, &schema, "").is_err(), "missing property");

    // A changed suite constant.
    let mut suite = original.clone();
    suite["suite"]["tag_len"] = json!(24);
    assert!(validate(&suite, &schema, "").is_err(), "wrong tag length");

    // And the untouched document still passes, so the checks above are
    // rejecting the mutation rather than the document.
    assert!(validate(&original, &schema, "").is_ok());
}

