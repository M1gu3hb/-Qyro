impl Plan {
    fn frame(&self) -> Frame {
        Frame::new(self.message_type, self.payload.clone())
            .expect("within limits")
            .with_flags(self.flags)
            .expect("transport flags only")
            // The session identifier here is deliberately wrong; the sealer
            // overwrites it, and the recorded header shows that it did.
            .with_identifiers(
                SessionId::ZERO,
                self.transfer_id,
                self.stream_id,
                self.item_id,
            )
    }
}

/// Everything one run produces.
struct Recorded {
    session_id: SessionId,
    auth_transcript: [u8; 32],
    initiator_to_responder_secret: [u8; 32],
    responder_to_initiator_secret: [u8; 32],
    initiator_sealer: FrameSealer,
    initiator_opener: FrameOpener,
    responder_sealer: FrameSealer,
    responder_opener: FrameOpener,
}

/// Runs the handshake the ordinary way and derives the frame crypto from it.
fn run() -> Recorded {
    let initiator = DeviceIdentity::from_test_seed(&INITIATOR_SEED);
    let responder = DeviceIdentity::from_test_seed(&RESPONDER_SEED);

    let (initiator_hello, awaiting_responder) = InitiatorStart::new(&initiator)
        .send_hello_with_entropy(entropy(0xA0))
        .expect("opens");
    let (responder_hello, awaiting_initiator_finish) = ResponderStart::new(&responder)
        .receive_initiator_hello(&initiator_hello, entropy(0xB0))
        .expect("accepts");
    let (initiator_finish, awaiting_responder_finish) = awaiting_responder
        .receive_responder_hello(&responder_hello)
        .expect("verifies");
    let pending = awaiting_initiator_finish
        .receive_initiator_finish(&initiator_finish)
        .expect("verifies");
    let responder_finish = *pending.encoded_finish();
    let established_responder = pending.confirm_sent();
    let established_initiator = awaiting_responder_finish
        .receive_responder_finish(&responder_finish)
        .expect("verifies");

    let session_id = established_initiator.session_id();
    let auth_transcript = established_initiator.auth_transcript_for_test();
    let initiator_to_responder_secret = *established_initiator.sending_key_bytes();
    let responder_to_initiator_secret = *established_initiator.receiving_key_bytes();

    let (initiator_sealer, initiator_opener) = established_initiator
        .into_frame_crypto()
        .expect("derives the initiator's frame crypto");
    let (responder_sealer, responder_opener) = established_responder
        .into_frame_crypto()
        .expect("derives the responder's frame crypto");

    Recorded {
        session_id,
        auth_transcript,
        initiator_to_responder_secret,
        responder_to_initiator_secret,
        initiator_sealer,
        initiator_opener,
        responder_sealer,
        responder_opener,
    }
}

/// Rebuilds the HKDF `info` for one label, exactly as ADR-0022 specifies.
///
/// Written out here from the ADR rather than calling `super::info_for`, so the
/// file records the specification and not this implementation's reading of it.
fn info_for(direction: &str, purpose: &str, auth: &[u8; 32], session: SessionId) -> Vec<u8> {
    let mut info = Vec::new();
    info.extend_from_slice(b"QYRO-AEAD-V1/");
    info.extend_from_slice(direction.as_bytes());
    info.push(b'/');
    info.extend_from_slice(purpose.as_bytes());
    info.push(0x00);
    info.extend_from_slice(auth);
    info.extend_from_slice(session.as_bytes());
    info
}

/// Expands one traffic secret to `N` bytes under one label, using HKDF directly.
fn expand<const N: usize>(secret: &[u8; 32], info: &[u8]) -> [u8; N] {
    let hkdf = Hkdf::<Sha256>::from_prk(secret).expect("a 32-byte PRK");
    let mut out = [0u8; N];
    hkdf.expand(info, &mut out).expect("a supported length");
    out
}

/// The derivation block for one direction, computed from primitives.
fn derivation(secret: &[u8; 32], direction: &str, auth: &[u8; 32], session: SessionId) -> Value {
    let info_key = info_for(direction, "key", auth, session);
    let info_nonce_prefix = info_for(direction, "nonce-prefix", auth, session);
    json!({
        "info_key": hex(&info_key),
        "info_nonce_prefix": hex(&info_nonce_prefix),
        "aead_key": hex(&expand::<AEAD_KEY_LEN>(secret, &info_key)),
        "nonce_prefix": hex(&expand::<NONCE_PREFIX_LEN>(secret, &info_nonce_prefix)),
    })
}

/// Seals one plan and records everything an implementer needs to reproduce it.
fn seal_and_record(sealer: &mut FrameSealer, plan: &Plan) -> Value {
    let sealed = sealer.seal(&plan.frame()).expect("seals");
    let envelope = sealed.envelope();
    let header = envelope.header();
    json!({
        "name": plan.name,
        "message_type": header.message_type().to_wire(),
        "flags": header.flags().bits(),
        "transfer_id": hex(&header.transfer_id().to_be_bytes()),
        "stream_id": hex(&header.stream_id().to_be_bytes()),
        "item_id": hex(&header.item_id().to_be_bytes()),
        "sequence": hex(&header.sequence().to_be_bytes()),
        "nonce": hex(&sealed.nonce()),
        "associated_data": hex(&envelope.associated_data()),
        "plaintext": hex(&plan.payload),
        "ciphertext": hex(envelope.ciphertext()),
        "tag": hex(envelope.tag()),
        "frame": hex(&sealed.encode()),
    })
}

/// Builds the vector document.
fn build_document() -> Value {
    let mut recorded = run();
    let session = recorded.session_id;
    let auth = recorded.auth_transcript;

    let initiator_frames: Vec<Value> = initiator_plan()
        .iter()
        .map(|plan| seal_and_record(&mut recorded.initiator_sealer, plan))
        .collect();
    let responder_frames: Vec<Value> = responder_plan()
        .iter()
        .map(|plan| seal_and_record(&mut recorded.responder_sealer, plan))
        .collect();

    json!({
        "_warning": "TEST ONLY - NEVER PRODUCTION. Every key and secret below is derived from published seeds and is therefore compromised by definition.",
        "format": "qyro-aead-v1",
        "specification": "docs/adr/ADR-0022-qyro1-frame-aead.md",
        "aead_algorithm": "ChaCha20-Poly1305, RFC 8439",
        "chained_from": "handshake-v1.json",
        "note": "The session below is the one handshake-v1.json records, run from the same seeds and the same entropy. Its traffic secrets are the input to the derivation here, so an implementation can verify the handshake first and continue straight into the frame layer. Associated data is the whole 48-byte header; altering any byte of it invalidates the tag.",
        "suite": {
            "aead_key_len": AEAD_KEY_LEN,
            "nonce_len": NONCE_LEN,
            "nonce_prefix_len": NONCE_PREFIX_LEN,
            "tag_len": TAG_LEN,
            "header_len": HEADER_LEN,
            "replay_window": REPLAY_WINDOW,
        },
        "session": {
            "session_id": hex(session.as_bytes()),
            "auth_transcript_hash": hex(&auth),
            "initiator_to_responder_traffic_secret": hex(&recorded.initiator_to_responder_secret),
            "responder_to_initiator_traffic_secret": hex(&recorded.responder_to_initiator_secret),
        },
        "derivation": {
            "initiator_to_responder": derivation(
                &recorded.initiator_to_responder_secret, "i2r", &auth, session),
            "responder_to_initiator": derivation(
                &recorded.responder_to_initiator_secret, "r2i", &auth, session),
        },
        "initiator_to_responder_frames": initiator_frames,
        "responder_to_initiator_frames": responder_frames,
    })
}

/// Renders the document exactly as the committed file stores it.
fn render(document: &Value) -> String {
    let mut text = serde_json::to_string_pretty(document).expect("serializable");
    text.push('\n');
    text
}

