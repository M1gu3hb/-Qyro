//! Interoperable frame-AEAD vectors: generation, verification and schema.
//!
//! Same reasoning as the handshake vectors, and the same three jobs. A Rust test
//! that seals a frame and opens it again proves that Rust agrees with Rust; it
//! does not show the format is unambiguous, and it is no help to someone writing
//! the Swift or Kotlin side.
//!
//! 1. **Generates** `docs/security/test-vectors/aead-v1.json` deterministically,
//!    from the same seeds and entropy as the committed handshake vector, so the
//!    two files are one chain: the traffic secrets this file expands are the
//!    ones that file records.
//! 2. **Checks** that regenerating reproduces the committed file byte for byte.
//! 3. **Verifies** every recorded value again from the primitives — HKDF-SHA256
//!    and ChaCha20-Poly1305 — without going through [`FrameSealer`]. If the
//!    sealer and the specification disagree, that is where it shows.
//!
//! There is a fourth file involved and it is not generated by anything here:
//! `rfc8439-chacha20poly1305.json` holds the RFC's own vectors, transcribed from
//! the RFC text. It pins the primitive; this file pins what Qyro does with it.

