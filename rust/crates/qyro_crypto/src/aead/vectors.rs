/// Reads a nested string field out of a document.
fn field(document: &Value, path: &[&str]) -> String {
    let mut node = document;
    for key in path {
        node = &node[*key];
    }
    node.as_str()
        .unwrap_or_else(|| panic!("{path:?} is a string"))
        .to_owned()
}

fn fixed<const N: usize>(document: &Value, path: &[&str]) -> [u8; N] {
    unhex(&field(document, path))
        .try_into()
        .unwrap_or_else(|_| panic!("{path:?} is {N} bytes"))
}

#[test]
fn every_recorded_value_verifies_against_the_primitives() {
    // Rebuilds each derived value and each tag from HKDF and ChaCha20-Poly1305
    // directly. Nothing here calls FrameSealer, so a change in the sealer that
    // also changed the vectors would still be caught: the file would stop
    // matching the specification even while matching the code.
    let document: Value = serde_json::from_str(COMMITTED).expect("valid JSON");

    let session_id: [u8; 8] = fixed(&document, &["session", "session_id"]);
    let session = SessionId::from_be_bytes(session_id);
    let auth: [u8; 32] = fixed(&document, &["session", "auth_transcript_hash"]);

    for (direction, secret_field, frames_field) in [
        (
            "i2r",
            "initiator_to_responder_traffic_secret",
            "initiator_to_responder_frames",
        ),
        (
            "r2i",
            "responder_to_initiator_traffic_secret",
            "responder_to_initiator_frames",
        ),
    ] {
        let block = if direction == "i2r" {
            "initiator_to_responder"
        } else {
            "responder_to_initiator"
        };
        let secret: [u8; 32] = fixed(&document, &["session", secret_field]);

        // --- derivation -----------------------------------------------------
        let info_key = info_for(direction, "key", &auth, session);
        let info_prefix = info_for(direction, "nonce-prefix", &auth, session);
        assert_eq!(
            hex(&info_key),
            field(&document, &["derivation", block, "info_key"]),
            "{direction}: the recorded key label is label || 0x00 || transcript || session"
        );
        assert_eq!(
            hex(&info_prefix),
            field(&document, &["derivation", block, "info_nonce_prefix"])
        );

        let key = expand::<AEAD_KEY_LEN>(&secret, &info_key);
        let prefix = expand::<NONCE_PREFIX_LEN>(&secret, &info_prefix);
        assert_eq!(
            hex(&key),
            field(&document, &["derivation", block, "aead_key"]),
            "{direction}: the recorded key is HKDF-Expand over the traffic secret"
        );
        assert_eq!(
            hex(&prefix),
            field(&document, &["derivation", block, "nonce_prefix"])
        );

        // --- frames ---------------------------------------------------------
        let frames = document[frames_field].as_array().expect("an array");
        assert!(!frames.is_empty(), "{direction}: frames are recorded");

        for (index, frame) in frames.iter().enumerate() {
            let sequence: [u8; 8] = fixed(frame, &["sequence"]);
            assert_eq!(
                u64::from_be_bytes(sequence),
                index as u64,
                "{direction}: sequences start at zero and increase by one"
            );

            let mut expected_nonce = [0u8; NONCE_LEN];
            expected_nonce[..NONCE_PREFIX_LEN].copy_from_slice(&prefix);
            expected_nonce[NONCE_PREFIX_LEN..].copy_from_slice(&sequence);
            assert_eq!(
                hex(&expected_nonce),
                field(frame, &["nonce"]),
                "{direction} frame {index}: the nonce is prefix || sequence"
            );

            let associated_data = unhex(&field(frame, &["associated_data"]));
            assert_eq!(
                associated_data.len(),
                HEADER_LEN,
                "the associated data is the whole header"
            );
            assert_eq!(
                &associated_data[16..24],
                &session_id[..],
                "the sealer stamped the session id into the header"
            );
            assert_eq!(&associated_data[40..48], &sequence[..]);

            let bytes = unhex(&field(frame, &["frame"]));
            assert_eq!(
                &bytes[..HEADER_LEN],
                &associated_data[..],
                "{direction} frame {index}: the header on the wire is the authenticated one"
            );

            let mut buffer = unhex(&field(frame, &["plaintext"]));
            let tag = ChaCha20Poly1305::new_from_slice(&key)
                .expect("a 32-byte key")
                .encrypt_inout_detached(
                    &expected_nonce.into(),
                    &associated_data,
                    buffer.as_mut_slice().into(),
                )
                .expect("seals");

            assert_eq!(
                hex(&buffer),
                field(frame, &["ciphertext"]),
                "{direction} frame {index}: ChaCha20-Poly1305 reproduces the ciphertext"
            );
            assert_eq!(
                hex(&tag),
                field(frame, &["tag"]),
                "{direction} frame {index}: and the tag"
            );
            assert_eq!(
                bytes,
                [&associated_data[..], &buffer[..], tag.as_slice()].concat(),
                "{direction} frame {index}: the frame is header || ciphertext || tag"
            );
        }
    }
}

#[test]
fn the_recorded_frames_open_through_the_decoder_and_the_opener() {
    // The other direction of the same claim: the bytes in the file are bytes an
    // ordinary receiver accepts, not just bytes this crate can regenerate.
    let document: Value = serde_json::from_str(COMMITTED).expect("valid JSON");
    let mut recorded = run();

    // The openers come from `into_frame_crypto`, not from hand-wired secrets.
    // Pairing them by hand is exactly the mistake this test exists to catch, and
    // the first draft of it made that mistake: it fed each opener the secret for
    // the direction it does not read, and every recorded frame failed to open.
    for (frames_field, opener) in [
        (
            "initiator_to_responder_frames",
            &mut recorded.responder_opener,
        ),
        (
            "responder_to_initiator_frames",
            &mut recorded.initiator_opener,
        ),
    ] {
        for frame in document[frames_field].as_array().expect("an array") {
            let bytes = unhex(&field(frame, &["frame"]));

            let mut decoder = FrameDecoder::new();
            decoder.push(&bytes).expect("within buffer");
            let envelope = match decoder.next_frame() {
                Ok(Some(DecodedFrame::Encrypted(envelope))) => envelope,
                other => panic!("a recorded frame decodes as an envelope, got {other:?}"),
            };

            let opened = opener.open(&envelope).expect("the recorded frame opens");
            assert_eq!(hex(opened.payload()), field(frame, &["plaintext"]));

            // And it opens exactly once.
            assert!(
                opener.open(&envelope).is_err(),
                "a recorded frame is not a licence to replay it"
            );
        }
    }
}

