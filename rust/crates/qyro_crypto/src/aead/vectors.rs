#[test]
fn the_chacha20poly1305_implementation_matches_rfc8439() {
    // The primitive, pinned against the RFC's own numbers rather than against
    // anything this repository produced. Both cases run in both directions: the
    // encryption vector is decrypted again and the decryption vector is
    // re-encrypted, so neither half is taken on trust.
    let document: Value = serde_json::from_str(RFC8439).expect("valid JSON");
    let cases = document["cases"].as_array().expect("an array of cases");
    assert_eq!(cases.len(), 2, "section 2.8.2 and appendix A.5");

    for case in cases {
        let name = field(case, &["name"]);
        let key = unhex(&field(case, &["key"]));
        let nonce: [u8; NONCE_LEN] = fixed(case, &["nonce"]);
        let associated_data = unhex(&field(case, &["associated_data"]));
        let plaintext = unhex(&field(case, &["plaintext"]));
        let expected_ciphertext = unhex(&field(case, &["ciphertext"]));
        let expected_tag = unhex(&field(case, &["tag"]));

        let cipher = ChaCha20Poly1305::new_from_slice(&key).expect("a 32-byte key");

        let mut buffer = plaintext.clone();
        let tag = cipher
            .encrypt_inout_detached(
                &nonce.into(),
                &associated_data,
                buffer.as_mut_slice().into(),
            )
            .expect("seals");
        assert_eq!(buffer, expected_ciphertext, "{name}: ciphertext");
        assert_eq!(tag.as_slice(), expected_tag, "{name}: tag");

        let mut buffer = expected_ciphertext.clone();
        let tag: [u8; TAG_LEN] = expected_tag.clone().try_into().expect("a 16-byte tag");
        cipher
            .decrypt_inout_detached(
                &nonce.into(),
                &associated_data,
                buffer.as_mut_slice().into(),
                &tag.into(),
            )
            .unwrap_or_else(|_| panic!("{name}: the RFC's own tag must verify"));
        assert_eq!(buffer, plaintext, "{name}: plaintext");

        // A single flipped bit anywhere must break it.
        for position in [0usize, associated_data.len() - 1] {
            let mut altered = associated_data.clone();
            altered[position] ^= 0x01;
            let mut buffer = expected_ciphertext.clone();
            assert!(
                cipher
                    .decrypt_inout_detached(
                        &nonce.into(),
                        &altered,
                        buffer.as_mut_slice().into(),
                        &tag.into(),
                    )
                    .is_err(),
                "{name}: altered associated data must not verify"
            );
        }
    }
}
